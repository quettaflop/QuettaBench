# One-time conversion: configs/workloads.json + configs/xval.yaml (as merged by
# xval_config) -> configs/models/, configs/grids.yaml, configs/hardware/,
# configs/runs/. Idempotent: rerunning rewrites the same bytes.
# Usage: python3 scripts/convert_workloads.py
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
from quettabench.config import xval_config

CONFIGS = REPO / "configs"
HEADER = ("# Generated by scripts/convert_workloads.py from configs/workloads.json"
          " + configs/xval.yaml.\n")

# Base workload of each model -> (model file stem, attention family).
MODELS = {
    "llama": ("llama31_8b", "dense"),
    "qwen": ("qwen35_9b", "hybrid"),
    "qwen3": ("qwen38_27b", "hybrid"),
    "deepseek": ("deepseek_v4_flash", "mla"),
    "glm53": ("glm53", "mla"),
    "glm53flash": ("glm53flash", "mla"),
}
# workloads.json key -> model yaml key, for keys a run may also override.
ENGINE_KEYS = {"name": "name", "dtype": "dtype", "weights_gib": "weights_gib",
               "maxlen": "max_model_len", "tp": "tp", "kv_dtype": "kv_dtype",
               "kv_bytes": "kv_bytes", "quant": "quant", "expert_parallel": "ep",
               "verified": "verified"}
# Facts that never vary per run: model yaml only.
MODEL_ONLY = ("bench", "comm_bound_bs", "engine_commit", "checkpoint")


def model_facts(wl, attention):
    """Model yaml body: engine facts, then the quettaserve/crossval/provenance blocks."""
    out = {ENGINE_KEYS[k]: wl[k] for k in ENGINE_KEYS if k in wl}
    out["attention"] = attention
    if "bench" in wl:
        b = wl["bench"]  # the ok regex stays out: the adapter derives it from the test name
        out["quettaserve"] = {"crate": b["crate"], "test": b["test"],
                              "env_prefix": b["env"], "family": b["family"]}
    if "comm_bound_bs" in wl:
        out["crossval"] = {"comm_bound_bs": wl["comm_bound_bs"]}
    prov = {k: wl[k] for k in ("engine_commit", "checkpoint") if k in wl}
    if prov:
        out["provenance"] = prov
    return out


def run_body(name, wl, base, stem):
    """Run yaml body: model ref, engine keys that differ from the model, grid mode."""
    for k in wl:
        if k not in ENGINE_KEYS and k != "grid" and k not in MODEL_ONLY:
            sys.exit(f"{name}: unknown workloads.json key {k!r}")
        if k in MODEL_ONLY and wl[k] != base.get(k):
            sys.exit(f"{name}: {k} differs from its model; it cannot be a run override")
    engine = {ENGINE_KEYS[k]: wl[k] for k in ENGINE_KEYS
              if k in wl and wl[k] != base.get(k) and k != "name"}
    if wl["name"] != base["name"]:
        sys.exit(f"{name}: model name {wl['name']!r} has no base workload")
    body = {"model": stem}
    if engine:
        body["engine"] = engine
    body["workload"] = {"kind": "grid"}
    body["mode"] = {"mode": "serve", "grid": wl["grid"]}
    return body


class _Dumper(yaml.SafeDumper):
    """Block style, except tuples, which print inline: [4096, 1]."""


_Dumper.add_representer(
    tuple, lambda d, v: d.represent_sequence("tag:yaml.org,2002:seq", v, flow_style=True))


def write(rel, body):
    path = CONFIGS / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + yaml.dump(body, Dumper=_Dumper, sort_keys=False))


def main():
    wls = xval_config.workloads()
    by_name = {wls[k]["name"]: (k, stem, att) for k, (stem, att) in MODELS.items()}
    for key, (stem, attention) in MODELS.items():
        write(f"models/{stem}.yaml", model_facts(wls[key], attention))
    for name, wl in wls.items():
        base_key, stem, _ = by_name[wl["name"]]
        write(f"runs/{name}.yaml", run_body(name, wl, wls[base_key], stem))
    grids = {k: [tuple(c) for c in cells] for k, cells in xval_config.grids().items()}
    write("grids.yaml", {"grids": grids, "step_points": tuple(xval_config.step_points())})
    for profile in ("pcie", "nvlink"):
        write(f"hardware/{profile}.yaml", {
            **xval_config.run_params(),
            "collective": xval_config.collective(profile=profile),
            "provision": xval_config.provision(),
        })


if __name__ == "__main__":
    main()
